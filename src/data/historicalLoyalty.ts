/**
 * 依據武將名稱、歷史劇本時期 (0~5)、是否為君主、角色職務與魅力值，計算精準史實初始忠誠度
 */
export function getInitialGeneralLoyalty(
  generalName: string,
  scenarioIndex: number,
  isRuler: boolean,
  role?: string,
  cha?: number
): number {
  if (isRuler) {
    return 100;
  }

  // 1. 若在史實忠誠度資料庫中有精密配置，優先取用該劇本時期數值
  const table = HISTORICAL_LOYALTY_TABLE[generalName];
  if (table && scenarioIndex >= 0 && scenarioIndex < table.length) {
    return table[scenarioIndex];
  }

  // 2. 備用動態演算法 (按職級與魅力值計算合理基礎忠誠度 75~95)
  const baseCha = cha || 60;
  let roleBonus = 0;
  if (role === '軍師') roleBonus = 8;
  else if (role === '大將') roleBonus = 6;
  else if (role === '參軍' || role === '主簿') roleBonus = 4;
  else if (role === '副將') roleBonus = 2;

  const calculated = 76 + Math.floor(baseCha / 10) + roleBonus;
  return Math.max(50, Math.min(98, calculated));
}

