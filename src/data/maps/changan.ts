export function getChanganMap(): GridCell[] {
  const grid: GridCell[] = [];
  
  // 25x25 神州Hex風格：關中長安戰略地形圖
  // 核心戰略行軍要道格局：
  // 1. 【東扼潼關】：南北皆為高聳山脈(M)夾峙，東西為平原大道(P)——中原大軍沿平原進軍，必須正面穿過潼關(G)入關！
  // 2. 【西扼散關】：南北皆為隴山絕壁(M)，西面外側為行軍平原道路(P)，東面通往關中腹地，唯有大散關(G)鎖守通道！
  // 3. 【南鎖武關】：東西兩側為秦嶺萬仞雪峰(M)，南北為峽谷大道(P)——荊襄大軍北伐必由南向北強攻武關(G)！
  // 4. 【北臨渭水】：深水(D)、淺灘(W)與渡口石橋，形成天然北面屏障！
  // 5. 【長安帝城】：居於中央平原腹地(4x3 精緻雄偉比例)，四通八達，四周有上林苑御林(T)與良田(P)！
  const template = [
    "MMMMHHPPPPWWDDDDDWWPPPPMM", // 0 (北山與渭水之源)
    "MMMHHPPPPWWDDDDDDDWWPPMMM", // 1
    "MMHHPPPWWDDDDDDDDDWWPPMMM", // 2
    "MHHPPPWWDDDDWWWWDDDWWPMMM", // 3 (奔騰渭水橫貫關中)
    "MMHPPWWDDDDWWPPWWDDDWWMMM", // 4
    "MMHPPWWDDDWWPPPPTWWDDWMMM", // 5 (北岸原野與樹林)
    "MMMPPWWDDWWPPPPPTTWWPWMMM", // 6 (渭水與黃河交匯之險)
    "MMMPPPPPWWPPPPPTTTTTTPMMM", // 7
    "MMMMMPPPPPPPPPTTTTTTTPMMM", // 8
    "MMMMMMMPPPPPPPPTTTTTTMMMM", // 9 (西散關北翼山嶽 / 東潼關北翼山嶽)
    "MMMMMMMPPPPPPPPPPPPPTMMMM", // 10
    "PPPGPPPPPPCCCCPPPPPPGPPPP", // 11 (【西散關大道 P-G-P】|【長安帝城 C】|【東潼關大道 P-G-P】)
    "PPPGPPPPPPCCKKPPPPPPGPPPP", // 12 (行軍通道：關外平原 P -> 關塞 G -> 關內平原 P，兩側皆為崇山夾峙！【長安太守府 K】)
    "MMMMMMMPPPCCCCPPPPPPTMMMM", // 13 (散關南翼山嶽 / 潼關南翼華山)
    "MMMMMMMPPPPPPPPPPPPPPMMMM", // 14
    "MMMMMHHPPPPPTTTTPPPPPMMMM", // 15
    "MMMMHHPTTTPTTTTTTPPPPMMMM", // 16 (上林苑皇家密林 T)
    "MMMMHPTTTTTTTTTTTTPPPMMMM", // 17
    "MMMMHPTTTTTTTTTTTPPHHMMMM", // 18
    "MMMMMMHHPPPPPPPPPHHHMMMMM", // 19 (終南山麓峽谷入口)
    "MMMMMMMMMHHPPPHHHMMMMMMMM", // 20 (武關北向關內行軍峽谷大道 P)
    "MMMMMMMMMMMGGMMMMMMMMMMMM", // 21 (【南武關 G】兩側為秦嶺萬仞絕壁 M，正扼峽谷孔道！)
    "MMMMMMMMMMMPPMMMMMMMMMMMM", // 22 (武關南向出境行軍大道 P)
    "MMMMMMMMMMMPPMMMMMMMMMMMM", // 23 (通往荊楚宛洛之驛道 P)
    "MMMMMMMMMMMPPMMMMMMMMMMMM", // 24 (邊界行軍通道 P)
  ];

  for (let row = 0; row < template.length; row++) {
    for (let col = 0; col < template[row].length; col++) {
      const char = template[row][col];
      grid.push({
        col,
        row,
        terrain: charToTerrain[char] || '平地'
      });
    }
  }

  return grid;
}
