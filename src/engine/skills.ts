/**
 * 取得武將可用戰鬥技能清單
 * 
 * 智能分配規則（針對非名將庫或動態生成武將）：
 * 1. 【防禦被動】：
 *    - 「沉著」：統帥/智力/政治 >= 78 且治軍嚴整沉著者
 *    - 「反計」：智力 >= 88 且謀略過人者
 * 2. 【戰鬥被動】：
 *    - 「無雙」：武力 >= 95 且 統率 >= 88（極稀有一騎當千）
 *    - 「奮發」：武力 >= 78 勇猛近戰猛將
 *    - 「回射」：武力 >= 82 或 (武力 >= 75 && 統率 >= 75) 善射將領
 *    - 「騎射」：武力 >= 80 且 具備騎兵戰術素養
 * 3. 【主動戰法/計略】：
 *    - 「鼓舞」：統率/魅力/武力 >= 58
 *    - 「收拾」：智力 >= 60 或 統率 >= 65
 *    - 「火箭」：武力 >= 65 或 (武力 >= 60 && 智力 >= 55)
 *    - 「亂射」：武力 >= 80
 *    - 「佈陣」：君主、軍師，或智力 >= 75
 *    - 「激勵」：魅力 >= 86 且君主/高統大帥
 */
export function getGeneralAvailableSkills(general: {
  name: string;
  str: number;
  int: number;
  hp?: number;
  pol?: number;
  cha?: number;
  role?: string;
  provinceId?: number | null;
  skills?: string[];
}): string[] {
  // 1. 若武將數據本身已有持久化 skills 且長度大於 0，直接使用
  if (general.skills && Array.isArray(general.skills) && general.skills.length > 0) {
    return general.skills.slice(0, 8);
  }

  // 2. 若在歷史名將技能庫中，返回精確配置
  if (HISTORICAL_GENERAL_SKILLS[general.name]) {
    return [...HISTORICAL_GENERAL_SKILLS[general.name]].slice(0, 8);
  }

  const str = general.str || 50;
  const int = general.int || 50;
  const hp = general.hp || 50;
  const pol = general.pol || 50;
  const cha = general.cha || 50;
  const role = general.role || '將領';

  // 3. 真正無能的雜魚判定（全能力 < 55）
  const isCompleteZayu = str < 55 && int < 55 && pol < 55 && cha < 55 && hp < 55 && role !== '君主' && role !== '軍師';
  if (isCompleteZayu) {
    return [];
  }

  const resultSkills = new Set<string>();

  // ─── 4. 被動特技自動判定 ───
  // 【無雙】：極度稀有的一騎當千霸者
  if (str >= 95 && hp >= 85) {
    resultSkills.add('無雙');
  }

  // 【奮發】：猛將近戰加成
  if (str >= 78) {
    resultSkills.add('奮發');
  }

  // 【沉著】：防禦與抗性
  if ((hp >= 80 && int >= 68) || (int >= 80 && hp >= 70) || (pol >= 82 && hp >= 65)) {
    resultSkills.add('沉著');
  }

  // 【反計】：智謀反彈
  if (int >= 88) {
    resultSkills.add('反計');
  }

  // 【回射】：弓術防禦反擊
  if (str >= 82 && hp >= 72) {
    resultSkills.add('回射');
  }

  // 【騎射】：騎兵弓射
  if (str >= 80 && (hp >= 70 || role === '君主')) {
    resultSkills.add('騎射');
  }

  // ─── 5. 主動戰法與計略判定 ───
  // 【佈陣】(Formation Shift)：需統帥或謀略達中上水準（統帥 >= 80 或 智謀 >= 85，或統智兼備 78/75）之大將與軍師方可擁有
  const isAboveAverageCommanderOrStrategist = (hp >= 80) || (int >= 85) || (hp >= 78 && int >= 75);
  if (isAboveAverageCommanderOrStrategist) {
    resultSkills.add('佈陣');
  }

  // 【鼓舞】(Morale Boost)：有基礎統帥、勇武或聲望的將領皆能提振士氣
  if (cha >= 58 || hp >= 58 || str >= 58 || int >= 60 || role === '君主' || role === '軍師') {
    resultSkills.add('鼓舞');
  }

  // 【收拾】(Restore Order)：智慮周全或沉著治軍型將領
  if (int >= 60 || hp >= 65 || pol >= 65) {
    resultSkills.add('收拾');
  }

  // 【火箭】(Fire Arrow)：具備弓術或武勇戰術底子的武將
  if (str >= 65 || (str >= 60 && int >= 55)) {
    resultSkills.add('火箭');
  }

  // 【亂射】(Barrage)：武勇出眾善於弓射壓制的將領
  if (str >= 80) {
    resultSkills.add('亂射');
  }

  // 【伏兵】(Ambush)：高智謀善於用計之良將
  if (int >= 82 && (str >= 65 || hp >= 65)) {
    resultSkills.add('伏兵');
  }

  // 【激勵】(Inspiration)：高魅力君主或名望統帥
  if (cha >= 88 && (role === '君主' || hp >= 80)) {
    resultSkills.add('激勵');
  }

  return Array.from(resultSkills).slice(0, 8);
}

/**
 * 取得武將擁有的被動特技清單 (包含沉著、反計、無雙、奮發、回射、騎射、藤甲)
 */
export function getGeneralPassives(general: {
  name: string;
  str?: number;
  int?: number;
  hp?: number;
  pol?: number;
  cha?: number;
  role?: string;
  provinceId?: number | null;
  skills?: string[];
  passives?: PassiveSkillId[];
}): PassiveSkillId[] {
  // 1. 若已有明確定義的 passives，直接回傳
  if (general.passives && Array.isArray(general.passives) && general.passives.length > 0) {
    return general.passives;
  }

  // 2. 從武將已習得的 skills 陣列中過濾出被動特技
  const allSkills = general.skills && general.skills.length > 0 
    ? general.skills 
    : getGeneralAvailableSkills({
        name: general.name,
        str: general.str || 50,
        int: general.int || 50,
        hp: general.hp,
        pol: general.pol,
        cha: general.cha,
        role: general.role,
        skills: general.skills
      });

  const passives = allSkills.filter(s => isPassiveSkill(s)) as PassiveSkillId[];
  return passives;
}

